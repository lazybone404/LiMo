# Style key 兼容层 — 旧 key → 新 key
# ═══════════════════════════════════════════════════════════════════════

STYLE_ALIAS: dict[str, str] = {
    "meeting_minutes": "meeting",
}


def normalize_style(style: str) -> str:
    """统一风格键名，兼容历史数据（如 meeting_minutes → meeting）"""
    return STYLE_ALIAS.get(style, style)
