"""退出码 —— CLI 与调用脚本（尤其是 agent）之间的契约。

| 码 | 含义 | 典型场景 |
|---|---|---|
| 0 | **成功**（含空结果） | 搜到 0 条也是成功 |
| 2 | 用法错误 | 参数不合法、选项冲突、`--local` 用在不支持它的命令上 |
| 3 | 未找到 | 资源 ID 不存在 / 该文档没有这个产物 |
| 4 | 后端不可达 | 未启动、连接被拒、超时 |
| 5 | 数据或响应异常 | 坏 ID、坏游标、响应不是预期结构 |
| 6 | 内部错误 | 未预期异常（有 traceback 进 stderr） |

⚠️ **「空」与「坏」必须分开**（这是本表存在的理由）：`limo list --folder-id nope`
返回 0 条是**正常结果**（exit 0），而 `limo get ../../etc` 是**坏输入**（exit 5）。
两者若都返回 1，agent 就无法判断「该换个关键词」还是「该报错停下」——它会一直重试
一个永远不会成功的调用。这是 doc3 §7 明确要求区分的那一档。
"""

